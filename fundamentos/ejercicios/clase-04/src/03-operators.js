// Operadores Arirméticos

const suma = 5 +3; // Suma (+)
console.log('Suma: ' + suma); // 8

const resta = 5 - 3; // Resta (-)       
console.log('Resta: ' + resta); // 2

const multiplicacion = 5 * 3; // Multiplicación (*)
console.log('Multiplicación: ' + multiplicacion); // 15

const division = 6 / 3; // División (/)
console.log('División: ' + division); // 2

const modulo = 5 % 3; // Módulo (%)
console.log('Módulo: ' + modulo); // 2

const potencia = 5 ** 3; // Potenciación (**)
console.log('Potencia: ' + potencia); // 125  


// Operadores de Asignación

let a = 5; 
a += 3; // Asignación con suma (+=) a = a + 3
console.log('Asignación suma: ' + a); // 8

let b = 5;
b -= 3; // Asignación con resta (-=) b = b - 3
console.log('Asignación resta: ' + b); // 2

let c = 5;
c *= 3; // Asignación con multiplicación (*=) c = c * 3
console.log('Asignación multiplicación: ' + c); // 15

let d = 6;
d /= 3; // Asignación con división (/=) d = d / 3
console.log('Asignación división: ' + d); // 2


// Operadores de incremento y decremento

let contador = 10;
contador++; // Incremento (++) contador = contador + 1
console.log('Incremento: ' + contador); // 11

contador--; // Decremento (--) contador = contador - 1
console.log('Decremento: ' + contador); // 9

console.log( 1 / 0 ); // Infinity
console.log( -1 / 0 ); // -Infinity
console.log( 0 / 0 ); // NaN
